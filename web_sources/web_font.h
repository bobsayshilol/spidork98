const CharData &get_font_data(char ch) {
    if ('a' <= ch && ch <= 'z') {
        return s_font_data[ch - 'a'];
    } else if ('A' <= ch && ch <= 'Z') {
        return s_font_data[26 + ch - 'A'];
    } else if ('0' <= ch && ch <= '9') {
        return s_font_data[26 + 26 + ch - '0'];
    } else if (ch == ' ') {
        return s_font_data[26 + 26 + 10 + 0];
    } else if (ch == '.') {
        return s_font_data[26 + 26 + 10 + 1];
    } else if (ch == '(') {
        return s_font_data[26 + 26 + 10 + 2];
    } else if (ch == ')') {
        return s_font_data[26 + 26 + 10 + 3];
    } else if (ch == '\xA2') {
        return s_font_data[26 + 26 + 10 + 4];
    } else if (ch == '\xA3') {
        return s_font_data[26 + 26 + 10 + 5];
    } else if (ch == ':') {
        return s_font_data[26 + 26 + 10 + 6];
    } else if (ch == '-') {
        return s_font_data[26 + 26 + 10 + 7];
    } else if (ch == ',') {
        return s_font_data[26 + 26 + 10 + 8];
    } else if (ch == '\'') {
        return s_font_data[26 + 26 + 10 + 9];
    } else if (ch == '!') {
        return s_font_data[26 + 26 + 10 + 10];
    } else if (ch == '[') {
        return s_font_data[26 + 26 + 10 + 11];
    } else if (ch == ']') {
        return s_font_data[26 + 26 + 10 + 12];
    } else if (ch == 0x5C) {
        return s_font_data[26 + 26 + 10 + 13];
    } else if (ch == '%') {
        return s_font_data[26 + 26 + 10 + 14];
    } else if (ch == '/') {
        return s_font_data[26 + 26 + 10 + 15];
    }
    logging::print(logging::Level::Warning, "Missing char: 0x%x\n", ch);
    return s_font_data[26 + 26 + 10 + 16]; // ?
    static_assert(std::size(s_font_data) == 26 + 26 + 10 + 17);
}
